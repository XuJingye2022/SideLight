import { chromium } from 'playwright-core'
const browser = await chromium.connectOverCDP('http://127.0.0.1:9222')
const context = browser.contexts()[0] ?? (await browser.newContext())
const page = await context.newPage()
await page.setViewportSize({ width: 1440, height: 900 })
const answers = ['E=mc^2']
page.on('dialog', (d) => void d.accept(answers.shift() ?? 'x'))
await page.goto('http://localhost:5173', { waitUntil: 'networkidle' })
await page.evaluate(() => localStorage.clear())
await page.reload({ waitUntil: 'networkidle' })
await page.waitForSelector('.doc-column .ProseMirror')
await page.waitForTimeout(400)
await page.locator('.editor').click()
await page.keyboard.press('Control+End')
await page.getByRole('button', { name: '插入 ▾' }).click()
await page.waitForTimeout(200)
await page.getByRole('button', { name: '公式', exact: true }).click()
await page.waitForTimeout(700)
const html = await page.locator('.editor').innerHTML()
const at = html.indexOf('katex')
console.log('snippet:', html.slice(Math.max(0, at - 220), at + 120))
await page.close()
await browser.close()
